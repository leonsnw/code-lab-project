  "- **return** devolve o valor e termina a função na hora. Imprimir não é o mesmo que retornar.",
  "",
  "Em C, uma função precisa ser declarada **antes** de ser usada; o costume é escrever as auxiliares em cima. Marcá-las como `static` diz que só este arquivo as usa.",
