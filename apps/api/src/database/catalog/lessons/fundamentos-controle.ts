  "",
  "```c",
  "/* for: soma de 1 até n, com acumulador */",
  "long long soma = 0;",
  "for (int i = 1; i <= n; i++) {",
  "    soma += i;",
  "}",
  "",
  "/* while: quantas vezes dá para dividir por 2 até chegar a 1 */",
  "int passos = 0;",
  "while (x > 1) {",
  "    x = x / 2;",
  "    passos++;",
  "}",
  "```",
  "",
  "Em Python, o `for` percorre um intervalo: `for i in range(1, n + 1):` vai de 1 até `n` (o fim do `range` não entra).",
  "",
  "## Acumuladores e contadores",
  "",
  "Dois padrões aparecem em quase todo laço:",
  "",
  "- **Acumulador**: começa com um valor neutro (0 para somas, 1 para produtos) e é atualizado a cada volta: `soma += i`.",
  "- **Contador**: começa em 0 e soma 1 a cada evento: `passos++`.",
  "",
  "Um truque que você vai usar muito: `n % 10` dá o último dígito de `n`, e `n / 10` (divisão inteira) o remove. Com um laço, isso percorre todos os dígitos de um número.",
  "",
  "## Condição de parada",
  "",
  "Todo laço precisa terminar. Antes de escrever o laço, responda:",
  "",
