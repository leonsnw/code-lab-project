  "    while (x > 0) {",
  "        soma += x % 10;",
  "        x /= 10;           /* muda a cópia local, não o valor de quem chamou */",
  "    }",
  "    return soma;           /* devolve o resultado e encerra a função */",
  "}",
  "```",
  "",
  "- **Parâmetros** são variáveis que recebem uma **cópia** dos valores passados (para números). Alterar `x` dentro da função não altera a variável de quem chamou.",
